// 3. 진료비 읽기 — 설계사가 넣은 값만. 없으면 ★추측하지 않는다.
// ═══════════════════════════════════════════════════════════════
function 진료비읽기(text, 진료비) {
  if (진료비 != null && String(진료비).trim() !== '') {
    const n = parseInt(String(진료비).replace(/[^\d]/g, ''), 10);
    return Number.isFinite(n) && n > 0 ? n : null;
  }
  const t = String(text || '');
  let m = t.match(/(?:진료비|치료비|병원비|손해액|수리비)\s*(\d{1,5}(?:,\d{3})*|\d+)\s*(억원|만원|원)?/);
  if (!m) return null;
  const n = parseInt(String(m[1]).replace(/,/g, ''), 10);
  const 단위 = (m[2] || '').replace(/\s/g, '');
  if (!Number.isFinite(n) || n <= 0) return null;
  return 단위 === '억원' ? n * 100000000 : (단위 === '만원' ? n * 10000 : n);
}

const 원표기 = (n) => Number(n).toLocaleString('ko-KR') + '원';

// ═══════════════════════════════════════════════════════════════
// 4. 참고 범위 — ★약관에서 읽은 비율이 있을 때만 만든다
// ═══════════════════════════════════════════════════════════════
/**
 * ★설계사가 "적용 비율"을 직접 고른(넣은) 경우에만 계산한다.
 *   지니야가 약관에서 %를 찾아 임의로 곱하지 않는다(위 사고 주석 참고).
 * @param {number} 진료비    설계사 입력
 * @param {number} 적용비율  설계사가 고른 % (없으면 계산하지 않는다)
 * @param {number} 자기부담금 설계사 입력(선택) — 진료비에서 먼저 뺀다
 * @param {number} 한도      설계사가 고른 상한(선택)
 */
function 참고범위(진료비, 적용비율, 자기부담금, 한도) {
  if (!진료비) return { 있음: false, 사유: '진료비(손해액)를 넣어주시면 참고 범위를 보여드릴 수 있어요' };
  const p = Number(적용비율);
  if (!Number.isFinite(p) || p <= 0 || p > 100) {
    return { 있음: false, 사유: '적용할 비율을 설계사님이 골라주셔야 계산합니다 — 약관에서 찾은 비율은 아래 후보로 보여드려요. ★지니야가 임의로 고르지 않습니다' };
  }
  const 공제 = Number(자기부담금) > 0 ? Number(자기부담금) : 0;
  const 기준 = Math.max(0, 진료비 - 공제);
  let 값 = Math.round(기준 * p / 100);
  let 한도적용 = null;
  if (Number(한도) > 0 && 값 > Number(한도)) { 값 = Number(한도); 한도적용 = Number(한도); }
  return {
    있음: true, 최소: 값, 최대: 값,
    계산식: `(${원표기(진료비)}${공제 ? ' − ' + 원표기(공제) : ''}) × ${p}%`
      + (한도적용 ? ` → 한도 ${원표기(한도적용)} 적용` : ''),
    적용비율: p, 자기부담금: 공제, 한도적용,
  };
}

