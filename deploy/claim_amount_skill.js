// 5. 구조 설명 — 약관 발췌만 근거로. 없으면 만들지 않는다.
// ═══════════════════════════════════════════════════════════════
const SYS = `너는 보험설계사를 돕는 비서다. 아래 [약관 발췌]만 근거로 "이 담보의 보험금이 어떤 요소로 정해지는가(지급 구조)"를 3~5줄로 쉽게 설명한다.
규칙:
① 발췌에 있는 내용만 쓴다. 절대 지어내지 않는다. 발췌에 없으면 "발췌에는 없어요"라고 한다.
② ★금액을 단정하지 마라. 얼마가 나온다고 말하지 마라. 구조(무엇에서 무엇을 빼고 몇 %인지)만 설명한다.
③ ★"산정"·"확정"이라는 낱말을 쓰지 마라. "참고"·"추정"으로 말해라.
④ 이 사고에 그 조항이 적용되는지는 네가 판단하지 마라. 판단은 손해사정·보험사 몫이라고 말해라.`;

async function 구조설명(question, 발췌) {
  if (!발췌 || !발췌.length) return null;
  const { an } = _clients();
  if (!an) return null;
  const ctx = 발췌.map((x, i) => `(${i + 1}) [p.${x.page}] ${x.text}`).join('\n\n');
  try {
    const r = await an.messages.create({
      model: ANSWER_MODEL, max_tokens: 500, system: SYS,
      messages: [{ role: 'user', content: `[질문] ${question}\n\n[약관 발췌]\n${ctx}` }],
    });
    const t = (r.content || []).filter((b) => b.type === 'text').map((b) => b.text).join('').trim();
    return t ? _금지어정리(t) : null;         // ★금지어 필터 통과 후에만 내보낸다
  } catch (e) { return null; }
}

