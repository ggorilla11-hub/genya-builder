// 7. 입구 — 문장 → 지급 구조 안내 (+ 진료비 있으면 참고 범위)
// ═══════════════════════════════════════════════════════════════
/**
 * @param {string} text   "김철수 무릎수술 삼성화재 실손, 대략 얼마 나와?"
 * @param {number|string} 진료비  설계사가 넣은 값(없으면 null) — ★추측하지 않는다
 */
async function explain(text, opts) {
  // opts = {진료비, 적용비율, 자기부담금, 한도} · 숫자 하나만 주면 진료비로 본다(옛 호출 호환)
  const o = (opts && typeof opts === 'object') ? opts : { 진료비: opts };
  const 진료비 = o.진료비;
  const q = String(text || '').trim();
  const 기본 = { 면책, 설계사전용, 안내: '지급 "구조" 안내입니다. 금액을 정하는 것이 아닙니다.' };
  if (!q) {
    return Object.assign({ ok: false, error: '어떤 담보인지 알려주세요. 예: "삼성화재 자기신체사고 지급 구조 알려줘"' }, 기본);
  }

  const 돈 = 진료비읽기(q, 진료비);
  const r = await 약관발췌(q);

  // ── 약관 근거 없음 → ★금액을 내지 않는다 ──
  if (!r.found) {
    return Object.assign({
      ok: true,
      약관근거: false,
      창고: 창고이름,
      사유: r.사유,
      찾아본곳: r.찾아본곳 || [],
      구조설명: null,
      참고범위: { 있음: false, 사유: '약관 근거를 못 찾아 금액은 내지 않았어요 (지어내지 않음)' },
      필요정보: 필요정보_기본.slice(),
      // ★어디를 찾아봤는지 정직히 알린다("없다"는 말이 게으른 답이 아니라는 증거)
      알림: [
        (r.찾아본곳 && r.찾아본곳.length)
          ? `약관 ${r.찾아본곳.length}곳을 찾아봤는데 이 질문에 맞는 근거가 없었어요.`
          : '약관 창고에서 근거를 못 찾았어요.',
        '보험사·상품명을 같이 말씀해 주시면 더 정확히 찾습니다. 없는 내용은 지어내지 않습니다.',
      ],
    }, 기본);
  }

  // ── 약관 근거 있음 → 원문 숫자로만 범위 ──
  const 비율들 = 비율뽑기(r.발췌);
  const 한도들 = 한도뽑기(r.발췌);
  const 범위 = 참고범위(돈, o.적용비율, o.자기부담금, o.한도);
  const 설명 = await 구조설명(q, r.발췌);

  const 알림 = [];
  if (!돈) 알림.push('진료비(손해액)를 넣어주시면 참고 범위를 함께 보여드려요.');
  if (돈 && !범위.있음) {
    알림.push('★지니야는 약관에서 찾은 % 중 어느 것이 이 사고에 적용되는지 스스로 고르지 않습니다.'
      + ' 같은 20%라도 보상비율일 수도, 자기부담금 비율일 수도 있기 때문이에요.'
      + ' 아래 후보에서 설계사님이 골라주시면 그때 범위를 보여드립니다.');
  }
  if (비율들.length) 알림.push(`약관 발췌에서 비율 후보 ${비율들.length}개를 찾았어요 — 문장을 보고 맞는 것을 고르세요.`);
  if (!비율들.length) 알림.push('이 발췌에는 비율(%)이 없어요. 다르게 물어보시면 다른 조항을 찾아볼게요.');
  알림.push('여기 보이는 비율·한도는 약관 발췌에서 그대로 읽은 값입니다. 이 사고에 그 조항이 적용되는지는 손해사정·보험사 확인이 필요합니다.');

  return Object.assign({
    ok: true,
    약관근거: true,
    창고: 창고이름,
    보험사: r.보험사 || null,
    상품군: r.상품군 || null,
    찾아본곳: r.찾아본곳 || [],
    출처: r.sources,
    페이지: r.pages,
    발췌: r.발췌.map((x) => ({ page: x.page, 보험사: x.보험사 || '', 상품: x.상품 || '', 원문: String(x.text).slice(0, 300) })),
    구조설명: 설명,
    진료비: 돈,
    진료비표기: 돈 ? 원표기(돈) : null,
    // ★약관에서 찾은 비율·한도는 "후보"로만 보여준다. 어느 것을 적용할지는 설계사가 고른다.
    비율후보: 비율들.map((b) => ({ 비율: b.값, 표기: b.값 + '%', page: b.page, 약관문장: b.문장 })),
    한도후보: 한도들.map((h) => ({ 원: h.원, 표기: 원표기(h.원), page: h.page, 약관문장: h.문장 })),
    참고범위: 범위.있음
      ? { 있음: true, 최소: 범위.최소, 최대: 범위.최대, 표기: `대략 ${원표기(범위.최소)} 참고 범위(추정)`,
          계산식: 범위.계산식, 적용비율: 범위.적용비율, 자기부담금: 범위.자기부담금, 한도적용: 범위.한도적용 }
      : 범위,
    필요정보: 범위.있음 ? [] : 필요정보_기본.slice(),
    알림: 알림.map(_금지어정리),
  }, 기본);
}

module.exports = {
  explain,
  약관발췌, 비율뽑기, 한도뽑기, 진료비읽기, 참고범위, 구조설명,
  _금지어정리, _금지어남음,
  면책, 설계사전용, 필요정보_기본,
  창고이름,
};
