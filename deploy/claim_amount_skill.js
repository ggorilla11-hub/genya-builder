// 2. ★숫자는 약관 원문에서만 뽑는다 (LLM이 만든 숫자는 절대 안 쓴다)
// ═══════════════════════════════════════════════════════════════
// ★★2026-07-29 실물 시험에서 잡은 사고 — 이 주석은 지우지 말 것.
//   예전엔 발췌에서 찾은 %를 그대로 곱해 범위를 만들었다. 그런데 자동차보험 약관 p.28의 20%는
//   ★보상비율이 아니라 자기부담금(공제) 비율이었다. 그걸 곱해 "대략 10만원"이라는 엉뚱한 답이
//   ★약관 페이지까지 달고 나왔다. 근거가 붙어 있어 더 믿게 되는, 지어내기보다 위험한 사고다.
//   → 기계는 "이 %가 무슨 %인지" 구분하지 못한다. 그래서 이제 ★자동으로 고르지 않는다.
//     약관에서 찾은 비율은 ★후보로만 보여주고, 어느 것을 적용할지는 ★설계사가 고른다.
//     (손해사정사 영역 침범 금지 원칙과도 정확히 맞는다 — 적용 여부 판단은 우리 몫이 아니다)

/** 같은 값·같은 문장은 한 번만 남긴다(같은 문장이 여러 발췌에 걸쳐 중복으로 나온다) */
function _중복제거(list, key) {
  const 본 = new Set(); const out = [];
  list.forEach((x) => { const k = key(x); if (!본.has(k)) { 본.add(k); out.push(x); } });
  return out;
}

/** 발췌 원문에서 "○○%" 를 전부 뽑는다 → [{값, page, 문장}] ★후보일 뿐, 자동 적용하지 않는다 */
function 비율뽑기(발췌) {
  const out = [];
  (발췌 || []).forEach((x) => {
    const t = String(x.text || '');
    const re = /(\d{1,3})\s*(?:%|퍼센트)/g;
    let m;
    while ((m = re.exec(t))) {
      const v = parseInt(m[1], 10);
      if (v > 0 && v <= 100) out.push({ 값: v, page: x.page, 문장: _문장뽑기(t, m.index) });
    }
  });
  return _중복제거(out, (x) => x.값 + '|' + x.page + '|' + x.문장);
}
/** 발췌 원문에서 금액 한도를 뽑는다 → [{원, page, 문장}] ★후보일 뿐, 자동 적용하지 않는다 */
function 한도뽑기(발췌) {
  const out = [];
  (발췌 || []).forEach((x) => {
    const t = String(x.text || '');
    const re = /(\d{1,3}(?:,\d{3})+|\d+)\s*(억\s*원|만\s*원|원)/g;
    let m;
    while ((m = re.exec(t))) {
      const n = parseInt(String(m[1]).replace(/,/g, ''), 10);
      const 단위 = m[2].replace(/\s/g, '');
      const 원 = 단위 === '억원' ? n * 100000000 : (단위 === '만원' ? n * 10000 : n);
      if (원 >= 10000) out.push({ 원, page: x.page, 문장: _문장뽑기(t, m.index) });
    }
  });
  return _중복제거(out, (x) => x.원 + '|' + x.page + '|' + x.문장);
}
/** 숫자가 나온 자리의 문장을 잘라 근거로 보여준다(원문 그대로 · 가공 안 함) */
function _문장뽑기(t, idx) {
  const s = Math.max(0, t.lastIndexOf('.', idx) + 1);
  let e = t.indexOf('.', idx); if (e < 0) e = Math.min(t.length, idx + 90);
  return t.slice(s, e + 1).trim().slice(0, 140);
}

