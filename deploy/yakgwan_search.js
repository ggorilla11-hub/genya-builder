  // ★표지 문제 수정(2026-07-29) — 시험이 밖에서 확인할 수 있게 연다
  검색어, 본문인가, 깨짐비율, 본문최소길이, 내용어힌트, 상품맞음, 상품명키워드, 기본후보수,
  핵심어, 핵심어포함수,
