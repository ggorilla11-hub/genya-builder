/**
 * @returns {Array} 뒤질 네임스페이스 목록(개수·최신 연도 우선)
 * ★한 곳만 고르지 않는다. 관련 후보를 여러 개 골라 점수로 판정한다.
 */
// ★★2026-07-29 실측으로 잡은 사고 — 이 주석 지우지 말 것.
//   예전엔 "확장 군 순서 → 연도 최신 → 개수" 로 골랐다. 그랬더니 후보 6칸 중 4칸을
//   ★8개·10개·6개짜리 옛 특별약관 조각이 차지하고, 정작 큰 창고가 빠졌다.
//     삼성화재/실손 → longterm 2023(8개)·2021(10개)·2020(8개)까지 뽑히고 health_2026(173,858) 탈락
//     현대해상/건강 → health 2023(6개)·2021(4개)이 자리 먹고 ★indemnity_2026(실손 전용) 탈락
//   그래서 "삼성화재 실손 본인부담금"에 ★재물보험(화재·급배수시설누출)이 나왔다(대표님 실측).
//   → 이제 ★각 군에서 큰 것부터 2곳씩 뽑고, 남는 자리를 큰 순으로 채운다.
const 큰순 = (a, b) => (b.개수 - a.개수) || (b.연도숫자 - a.연도숫자);

function 후보고르기(맵, 보험사, 상품군, 후보수) {
  const N = 후보수 || 기본후보수;
  let 목록 = 맵.slice();
  if (보험사) {
    const 좁힘 = 목록.filter((x) => x.보험사 === 보험사);
    if (좁힘.length) 목록 = 좁힘;               // 그 보험사 약관이 하나도 없으면 전체로 둔다(정직히 알림)
  }
  if (상품군 && 군확장[상품군]) {
    const 군들 = 군확장[상품군];
    const 안 = 목록.filter((x) => 군들.includes(x.상품군코드));
    if (안.length) {
      const 고름 = [];
      // ① 관련 군마다 ★큰 창고 2곳씩 — 작은 옛 조각이 자리를 먹지 못하게
      군들.forEach((g) => {
        안.filter((x) => x.상품군코드 === g).sort(큰순).slice(0, 2)
          .forEach((x) => { if (!고름.includes(x)) 고름.push(x); });
      });
      // ② 남은 자리는 관련 군 전체에서 큰 순으로
      안.slice().sort(큰순).forEach((x) => { if (고름.length < N && !고름.includes(x)) 고름.push(x); });
      return 고름.slice(0, N);
    }
  }
  // 상품군을 못 정했으면 ★큰 창고 위주로 넓게 훑는다(점수가 걸러준다)
  return 목록.slice().sort(큰순).slice(0, N);
}

