// 2-2. ★표지(p.1)만 가져오던 문제 (2026-07-29 대표님 실측 신고)
// ═══════════════════════════════════════════════════════════════
// [증상] "삼성화재 실손 본인부담금 지급 구조" → 문서는 맞는데 ★전부 p.1 표지만 왔다.
