//        질문에 "삼성화재 실손"처럼 ★보험사·상품명이 들어가면 표지와 거의 완벽히 겹쳐 이긴다.
//        (상품명이 없는 질문 "암 진단비 면책 기간"은 본문 p.16·26·28이 정상으로 나왔다)
// [실측] 같은 질문에서 보험사명만 빼니 1위가 p.1(94자) → ★p.8(900자 본문)로 바뀌었다.
//        내용어 위주로 물으니 p.29 본인부담금 보상제 · p.67 보상비율(Co-insurance)까지 나왔다.
// [수정] ① 검색어에서 보험사명을 뺀다(보험사는 이미 네임스페이스 고를 때 쓰므로 손실 0)
//        ② 표지·목차 조각은 본문 뒤로 민다  ③ 본문이 하나도 없으면 내용어를 보강해 한 번 더 찾는다
//        ④ 같은 문장이 여러 상품에 똑같이 들어있어 중복으로 자리를 먹던 것도 정리한다

const 본문최소길이 = 180;   // 실측: 표지 94~110자 · 목차조각 19~59자 · 본문 200~900자

/** 글자 깨짐 비율 — 표지는 디자인 폰트라 추출이 깨진다(੉약관਷Әਲ਼ … 같은 글자) */
function 깨짐비율(t) {
  const s = String(t || '');
  if (!s.length) return 1;
  // 정상 = 한글 완성형·한자·영숫자·공백·흔한 문장부호. 그 밖(자모 분리·타 문자셋)은 깨진 것으로 본다.
  const 이상 = s.replace(/[가-힣一-龥A-Za-z0-9\s.,·:;()\[\]{}<>「」『』%\-–—/‘’“”"'?!&+*=~@#₩$|\\°㎡㎏]/g, '');
  return 이상.length / s.length;
}

/** 이 청크가 "본문"인가 — 표지·목차 조각이면 false */
function 본문인가(text) {
  const s = String(text || '');
  return s.length >= 본문최소길이 && 깨짐비율(s) < 0.15;
}

/** 검색어 정제 — ★보험사명을 뺀다(표지가 이기는 것을 막는다) */
function 검색어(질문) {
  let t = String(질문 || '');
  보험사별칭.forEach(([, re]) => { t = t.replace(new RegExp(re.source, 'gi'), ' '); });
  t = t.replace(/\s+/g, ' ').trim();
  return t.length >= 2 ? t : String(질문 || '');   // 다 지워지면 원문을 쓴다(빈 검색 방지)
}

