// 2-1. ★"약관 질문인가?" 판별 — 대화 두뇌가 창고를 부를지 정하는 문
// ═══════════════════════════════════════════════════════════════
// [사고 2026-07-29 대표님 실측] "현대해상 암진단비 면책기간은?" 이라고 물었더니
//   지니야가 ★창고를 찾아보지도 않고 이론으로 답하고 "약관을 올려달라"고 했다.
//   창고엔 현대해상 약관이 26종·163,353개나 있는데 ★없는 것처럼 굴었다.
// [원인] main_server의 약관 분기 조건이 ★자동차보험 시절 낱말만 보고 있었다:
//          /약관|무보험|대물|자기신체|자동차상해|담보|보장.*(뭐|무엇|차이)/
//        "암진단비 면책기간"은 여기 하나도 안 걸려서 일반 대화로 새 나갔다.
// [수정] 판별을 ★이 공용 모듈로 옮긴다. 창고가 넓어지면 여기만 고치면 되고,
//        다른 기능(상담·상품추천)도 같은 판별을 그대로 쓴다(문 열어두기).

// 약관을 봐야 답할 수 있는 낱말들(보험사·상품군을 안 써도 이것만으로 약관 질문이다)
const _약관의도 = /약관|면책|감액|담보|특약|보상하는\s*손해|보상하지\s*않|지급\s*(조건|기준|사유|구조|한도|제외)|자기부담|본인부담|공제\s*금액|보장\s*(내용|범위|한도|되나|되는지|받나)|가입금액|보험금\s*(지급|얼마|기준)/;
// 물어보는 말투(보험사·상품군만 나와도 질문이면 창고를 본다)
const _물음 = /\?|나요|가요|인가|얼마|어떻게|어떤|무엇|뭐|되나|되는지|알려|설명|차이|기간|조건|기준|해줘|알고/;

/**
 * 이 질문에 약관 창고를 찾아봐야 하는가.
 * ★"올려달라"고 하기 전에 ★창고부터 뒤지게 하는 문(회장님 지시 2026-07-29).
 */
// ★가로채면 안 되는 것들 — 대화 라우터에서 이 분기 ★뒤에 오는 기능들의 몫이다.
//   (만기·명단 / 증권·드라이브 / 일정·브리핑 / 발송·결재는 앞 분기가 가져가지만, 이중 안전핀을 둔다)
//   약관 의도어가 분명히 있으면 이 제외는 무시한다("암보험 약관 면책기간" 같은 질문은 약관이 맞다).
const _약관아님 = /만기|명단|고객\s*(목록|전체|정리|누구)|증권|드라이브|파일\s*찾|일정|브리핑|아침|발송|결재|추천\s*(해|좀|해줘)?|설계\s*(해|서)|보험료\s*(얼마|계산)|가입\s*(할까|해야|하면\s*좋)/;

/**
 * 이 질문에 약관 창고를 찾아봐야 하는가.
 * ★"올려달라"고 하기 전에 ★창고부터 뒤지게 하는 문(회장님 지시 2026-07-29).
 */
function 약관질문인가(q) {
  const t = String(q || '').trim();
  if (!t) return false;
  if (_약관의도.test(t)) return true;          // 약관 낱말이 분명하면 무조건 창고
  if (_약관아님.test(t)) return false;         // 다른 기능 몫이면 넘긴다
  const 보험사 = 보험사찾기(t);
  const 상품군 = 상품군찾기(t);
  return !!((보험사 || 상품군) && _물음.test(t));
}

