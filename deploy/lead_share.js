// lead_share.js — ⚖️ 밤샘 발굴 리드 배분 (2026-07-27 대표님 확정)
//
// ★★이 파일은 ★나누기만 한다. 발굴도 저장도 발송도 하지 않는다 — 순수 계산.
//   그래서 서버가 실수로도 발송할 수 없다(할 줄 아는 코드가 여기 없다).
//
// ★왜 "직업별로 한 번만 발굴하고 나눠주는가":
//   대표마다 따로 발굴하면 재무설계사가 10명일 때 ★같은 검색을 10번 돌린다.
//   API 할당량이 10배로 나가고, 더 나쁜 건 ★10명이 같은 글을 받아
//   한 사람에게 답글이 10개 달린다 — 민원이다.
//   → 직업별로 딱 한 번 발굴하고, 그 직업 사람들에게 ★겹치지 않게 나눈다.
//
// ★규칙(2026-07-27 대표님 확정)
//   ① 배분 기준 = ★검수 "이전"(발굴 원본). 검수 통과분이 아니라 발굴된 그대로 나눈다.
//      검수는 그 뒤에 각자 화면에서 돈다 — 배분을 검수까지 기다리게 하지 않는다.
//   ② 재무·보험 = 오상열 대표와 같은 직업
//        · 교육생: 하루 ★10개 상한
//        · 오대표: 무제한 — ★나머지 전부
//   ③ 그 밖의 직업(학원·필라테스·세무…)
//        · 그 직업으로 밤샘 켠 사람 수로 ★1/n. 오대표는 안 낀다.
//   ④ 나누는 순서: 점수 높은 순으로 줄 세워 ★번갈아(라운드로빈).
//        매일 ★시작 순서를 한 칸씩 돌려, 특정인이 계속 1등을 받지 않게 한다.
//   ⑤ ★핫 리드는 상위 20개로 본다(보고·정렬 기준).

const 하루상한 = Number(process.env.LEAD_DAILY_CAP) || 10;   // 재무·보험 교육생 하루 몫
const 핫상위 = Number(process.env.LEAD_HOT_TOP) || 20;        // ★핫 리드는 점수 높은 상위 20개
const 재무직업 = /(재무|보험|설계사|insurance|financial|fp|cfp)/i;

function 재무인가(직업) { return 재무직업.test(String(직업 || '')); }

// ★쓰지 않는다(배분은 검수 이전 기준) — 아침 화면이 "핫"을 셀 때만 참고한다
function 통과인가(x) {
  const v = String((x && (x.판정 || x.verdict)) || '');
  const g = String((x && (x.등급 || x.grade || x.tier)) || '');
  if (/공급자|경쟁자|홍보|제외|반려/.test(v)) return false;
  return v === '고객' || /^(A|B|S)$/i.test(g) || Number((x && x.점수) || 0) >= 40;
}
function 좋은순(a, b) {
  const p = (x) => (x.판정 === '고객' ? 1000 : 0) + Number(x.점수 || 0) + (/^(A|S)$/i.test(String(x.등급 || '')) ? 100 : 0);
  return p(b) - p(a);
}

// 오늘이 며칠인가로 시작 순서를 돌린다(같은 사람이 계속 1등을 받지 않게)
function _오프셋(n, 날짜) {
  if (n <= 1) return 0;
  const d = String(날짜 || new Date().toISOString()).slice(0, 10).replace(/-/g, '');
  return (Number(d) || 0) % n;
}

// ═══ 나누기 ═══
//   대표들 = [{ 지문, 직업, vip:true|false }]
//   리드   = [{ 채널, 링크, 발췌, 등급, 점수, 판정 }]
//   돌려주는 것 = { 몫: { 지문: [리드…] }, 설명: '…' }
function 나누기(직업, 리드, 대표들, opts) {
  const o = opts || {};
  const 상한 = Number(o.상한) || 하루상한;
  // ★대표님 확정: 배분은 ★검수 이전(발굴 원본) 기준. 거르지 않고 점수 높은 순으로 그대로 나눈다.
  const 목록 = (리드 || []).slice().sort(좋은순);
  const 쓸수있는 = 목록;
  const 나머지목록 = [];
  const 몫 = {};
  (대표들 || []).forEach((p) => { 몫[p.지문] = []; });
  if (!대표들 || !대표들.length) return { 몫, 설명: '이 직업으로 밤샘을 켠 분이 없어요' };

  const vip = 대표들.find((p) => p.vip);
  const 교육생 = 대표들.filter((p) => !p.vip);

  // ① 재무·보험 — 교육생 10개씩, 나머지는 전부 오대표
  if (재무인가(직업) && vip) {
    let i = 0;
    const 시작 = _오프셋(교육생.length, o.날짜);
    for (const x of 쓸수있는) {
      let 담김 = false;
      // 번갈아 돌면서 아직 상한에 안 찬 교육생에게 한 장씩
      for (let k = 0; k < 교육생.length; k++) {
        const p = 교육생[(시작 + i + k) % 교육생.length];
        if (몫[p.지문].length < 상한) { 몫[p.지문].push(x); i++; 담김 = true; break; }
      }
      if (!담김) 몫[vip.지문].push(x);            // 교육생이 다 찼으면 오대표
    }
    몫[vip.지문].sort(좋은순);                        // ★핫 리드가 앞에 오게
    return { 몫, 설명: `재무·보험 — 교육생 ${교육생.length}명에게 각 최대 ${상한}개(검수 이전 기준), 나머지 ${몫[vip.지문].length}개는 오대표` };
  }

  // ② 그 밖의 직업 — 켠 사람 수로 1/n (오대표는 안 낀다)
  const 대상 = 교육생.length ? 교육생 : 대표들.filter((p) => !p.vip || 대표들.length === 1);
  if (!대상.length) return { 몫, 설명: '이 직업으로 밤샘을 켠 교육생이 없어요' };
  const 시작 = _오프셋(대상.length, o.날짜);
  쓸수있는.forEach((x, i) => { 몫[대상[(시작 + i) % 대상.length].지문].push(x); });
  const 각 = Math.floor(쓸수있는.length / 대상.length);
  return { 몫, 설명: `${직업 || '그 밖의 직업'} — ${대상.length}명이 ${쓸수있는.length}개를 나눔(각 ${각}개 안팎, 점수 높은 순 번갈아)` };
}

// ★핫 리드 = ★상위 20개 안에서 ★실제로 핫인 것만(대표님 확정: "핫 상위 20개 기준").
//   몫이 2개인데 "핫 2건"이라 하면 부풀린 말이 된다 — 있는 그대로만 센다.
function 핫인가(x) {
  return /^(A|S)$/i.test(String((x && (x.등급 || x.grade || x.tier)) || ''))
    || Number((x && x.점수) || 0) >= 60
    || String((x && (x.판정 || x.verdict)) || '') === '고객';
}
function 핫세기(몫리드) { return (몫리드 || []).slice(0, 핫상위).filter(핫인가).length; }

module.exports = { 나누기, 재무인가, 통과인가, 핫인가, 좋은순, 핫세기, 하루상한, 핫상위 };
