// ─────────────────────────────────────────────────────────────
// lead_filter.js — 🔍 발굴 대상 판별 (독립 모듈 · 모든 채널 AI 공용)
//
// 무엇을·왜: 발굴이 "도움을 원하는 고객"이 아니라 "홍보하는 공급자(경쟁자)"를 물어왔다.
//   원인은 등급 규칙이 거꾸로였다 — '상담·문의·카톡·연락'을 🔥핫으로 쳤는데,
//   그건 고객이 원하는 신호가 아니라 광고하는 사람이 뿌리는 신호다.
//   "상담 문의는 카톡 주세요"라고 광고하는 경쟁자가 1순위로 올라왔다.
//   → 남의 홍보 댓글에 답글을 달면 대표님 평판이 상한다. 발굴 품질의 핵심 결함.
//
// ★판별 2단계(비용·정확도 균형)
//   1단계 규칙: 명백한 공급자 신호(연락처·해드립니다·직함)는 LLM 없이 즉시 제외 — 싸고 확실
//   2단계 LLM: 애매한 것만 맥락으로 판단 — 규칙으로 못 잡는 미묘한 홍보를 거른다
//
// ★애매하면 버리지 않고 "확인 필요"로 사람에게 넘긴다(놓침도 사고, 오인도 사고).
// ★자동 댓글·발송 없음. 이 모듈은 "누구를 보여줄지" 고르기만 한다.
// ─────────────────────────────────────────────────────────────
'use strict';

// ── 공급자(홍보자·경쟁자) 신호 — 있으면 고객이 아니다 ──
//   ①연락 유도: 자기에게 연락하라고 하는 말
const SUP_CONTACT = /(문의\s*(주|바랍|환영)|연락\s*(주|바랍|환영)|디엠\s*주|dm\s*주|카톡\s*(주|아이디|id)|톡\s*주|오픈\s*채팅|오픈카톡|프로필\s*(링크|참고|확인)|링크\s*(참고|확인|클릭)|아래\s*링크|댓글\s*남겨주시면|남겨주시면\s*(연락|안내))/i;
//   ②서비스 제공: 내가 해주겠다는 말(고객은 이렇게 말하지 않는다)
const SUP_OFFER = /(해\s*드립니다|해\s*드려요|해\s*드릴|도와\s*드립니다|도와\s*드려요|알려\s*드립니다|알려\s*드려요|안내\s*(해\s*드|드립)|무료\s*(상담|진단|컨설팅|점검)|상담\s*(가능|환영|해\s*드)|설계\s*해\s*드|맞춤\s*설계|1:1\s*(상담|코칭)|수익\s*보장|원금\s*보장)/;
//   ③직함·업계: 자기 신분을 밝히는 공급자
const SUP_TITLE = /(설계사|재무설계사|자산관리사|플래너|컨설턴트|상담사|세무사|회계사|전문가입니다|대표입니다|원장입니다|팀장입니다|지점장|영업|모집인|GA\b)/;
//   ④연락처 노출: 번호·아이디를 적어둔 것
const SUP_NUMBER = /(01[016789][-\s.]?\d{3,4}[-\s.]?\d{4}|\b\d{3,4}[-\s.]\d{4}\b|@[a-zA-Z0-9_]{4,}|(kakao|카카오)\s*[:：]|https?:\/\/)/i;

// ── 수요자(진짜 고객) 신호 — 도움을 "받고 싶은" 사람 ──
const DEM_ASK = /(고민|막막|어떻게\s*(해야|하죠|하나요|할까)|어떡|모르겠|답답|불안|걱정|무섭|초보|처음|시작하고\s*싶|배우고\s*싶|알고\s*싶|궁금|여쭤|여쭙|질문|조언|추천\s*(해\s*주|부탁)|알려\s*주세요|도와\s*주세요|가능할까요|괜찮을까요|맞을까요|해야\s*할까요|어디서|얼마나|얼마를)/;
//   더 뜨거운 수요 — 지금 도움을 구하는 말
const DEM_HOT = /(상담\s*(받고|받을|받고\s*싶|가능한가|받으려)|도움\s*(받고|주실|필요)|봐\s*주실|점검\s*받고|진단\s*받고|알아보고\s*싶|시작하려|급해|절실)/;

/**
 * 1단계 규칙 판별(LLM 없이). 명백한 것만 결론내고 나머지는 '애매'로 넘긴다.
 * @returns {{verdict:'공급자'|'고객'|'애매', reasons:string[], demand:boolean}}
 */
function preScreen(text, opts) {
  opts = opts || {};
  const t = String(text || '');
  const reasons = [];
  if (!t.trim()) return { verdict: '공급자', reasons: ['빈 내용'], demand: false };

  // ★채널 주인이 자기 영상에 단 댓글 = 자기 홍보. 고객이 아니다.
  if (opts.authorChannelId && opts.videoChannelId && opts.authorChannelId === opts.videoChannelId) {
    return { verdict: '공급자', reasons: ['채널 주인 본인 댓글(자기 홍보)'], demand: false };
  }
  if (SUP_CONTACT.test(t)) reasons.push('연락 유도(문의·카톡·링크)');
  if (SUP_OFFER.test(t)) reasons.push('서비스 제공 표현(해드립니다·무료상담)');
  // ★2026-08-09 B트랙(b2b) 신호 — 이때만 ★직함 검사를 건너뛴다.
  //   왜: B트랙이 찾는 사람이 바로 ★설계사·원장·세무사·지점장이다. 그들이 신분을 밝히는 것은
  //       "경쟁자"라는 뜻이 아니라 "찾던 사람"이라는 뜻이다(A트랙에서는 정반대다).
  //   ★신호가 없으면 아래 한 줄은 예전과 완전히 같다 — A트랙·밤샘·화면 일반 발굴 무접촉.
  //   ★직함만 눈감아 준다. 연락 유도·해드립니다·연락처·링크는 b2b여도 그대로 공급자다
  //     (진짜 광고·경쟁자는 여전히 거른다 — 남의 홍보글에 답글 다는 사고는 트랙과 무관하다).
  if (!opts.b2b && SUP_TITLE.test(t)) reasons.push('업계 직함 노출');
  if (SUP_NUMBER.test(t)) reasons.push('연락처·아이디·링크 노출');

  const demand = DEM_ASK.test(t) || DEM_HOT.test(t);
  // 공급자 신호가 하나라도 있으면 제외. 수요 표현이 섞여 있어도 광고문에 흔히 같이 쓰인다.
  if (reasons.length) return { verdict: '공급자', reasons, demand };
  if (demand) return { verdict: '고객', reasons: ['도움을 구하는 표현'], demand: true };
  // 수요 신호도 공급 신호도 없음 → 단순 감상·잡담일 확률이 높지만 단정하지 않는다
  return { verdict: '애매', reasons: ['고민·질문 표현이 뚜렷하지 않음'], demand: false };
}

/**
 * 온도 등급 — ★수요 표현만 본다. 예전엔 '상담·문의·카톡'을 핫으로 쳐서
 * 광고하는 경쟁자가 1순위로 올라왔다(이번 사고의 직접 원인).
 */
function tier(text) {
  const t = String(text || '');
  if (DEM_HOT.test(t)) return '🔥핫';
  if (DEM_ASK.test(t)) return '🌤웜';
  return '🌱콜드';
}

/** LLM 판별용 프롬프트 — 규칙으로 못 가른 '애매'만 맥락으로 본다. */
function judgePrompt(items) {
  return `아래는 공개 댓글 목록이다. 각각이 "재무·보험 도움을 받고 싶어 하는 일반인(수요자)"인지,
"자기 서비스를 홍보하는 사람(공급자·경쟁자)"인지 판단해라.

[판단 기준]
· 고객(수요자): 자기 고민·상황을 말하고 답을 구한다. "어떻게 해야 할까요", "막막해요", "추천 부탁드려요"
· 공급자(경쟁자): 자기가 도와주겠다고 한다. 연락처·카톡·링크를 남긴다. 직함을 밝힌다.
  "상담해드립니다", "문의 주세요", "프로필 링크 참고", "○○설계사입니다"
· 애매: 둘 다 아니거나 판단이 어렵다. 단순 감상·잡담·무관한 내용.

★확신이 없으면 '고객'으로 몰지 말고 '애매'로 둔다. 잘못 접근하면 상대에게 실례가 된다.

JSON 배열만 출력. 설명 금지.
[{"i":0,"verdict":"고객|공급자|애매","why":"15자 이내"}]

[댓글]
${items.map((x, i) => `${i}. ${String(x).slice(0, 200)}`).join('\n')}`;
}

module.exports = { preScreen, tier, judgePrompt };
