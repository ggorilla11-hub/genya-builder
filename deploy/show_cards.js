// ⑥ 도움말
const 도움 = /(뭘|뭐를|뭐|무엇을|어떤\s*걸?|뭐가\s*돼|명령|기능).{0,12}(보여|알려|줄\s*수|할\s*수|되나|있어|있나)|도움말|사용법|어떻게\s*쓰/;

function 개수(q) { const m = String(q).match(/(\d+)\s*(명|개|건)/); return m ? Math.max(1, Math.min(50, Number(m[1]))) : 0; }
function 점수(q) { const m = String(q).match(/(\d+)\s*점\s*이상/); return m ? Number(m[1]) : 0; }
function 채널(q) {
  const t = [[/유튜브|youtube/i, '📺 유튜브'], [/지식\s*i?n|지식인/i, '🟢 네이버 지식iN'],
    [/다음\s*카페/i, '🟠 다음 카페'], [/네이버\s*카페|네카페/i, '🟩 네이버 카페'],
    [/블로그/i, '🔵 네이버 블로그'], [/뉴스/i, '📰 네이버 뉴스'], [/구글|google/i, '🔎 구글 검색']];
  return (t.find(([re]) => re.test(q)) || [])[1] || '';
}

// ★한 곳에서만 정한다 — 진단 창구(/api/diag/show)도 이 함수를 쓴다
function parse(q) {
  q = String(q || '');
  if (!q.trim()) return null;
  if (도움.test(q)) return { 종류: 'help', 제목: '👀 제가 보여드릴 수 있는 것' };
  if (양보.test(q)) return null;             // 기존 라우터 몫은 절대 가로채지 않는다
  // ★"밤샘 발굴 켜기"·"총 발굴 몇 명?"처럼 ★"보여줘"가 안 붙는 말은 그 관문 앞에서 먼저 받는다.
  const 먼저 = ['night_set', 'job_switch', 'job_try', 'draft_leads', 'lead_count'];
  for (const k of 먼저) {
    const r = 규칙.find((x) => x.종류 === k);
    if (r && r.re.test(q)) return { 종류: k, 제목: r.제목, 개수: 개수(q), 최소점수: 0, 채널: 채널(q), 원문: q.slice(0, 60) };
  }
  if (!보여.test(q)) return null;            // "보여줘" 계열이 아니면 손대지 않는다
  for (const r of 규칙) {
    if (!r.re.test(q)) continue;
    return { 종류: r.종류, 제목: r.제목, 개수: 개수(q), 최소점수: 점수(q) || (r.종류 === 'lead_score' ? 80 : 0), 채널: 채널(q) };
  }
  if (명단조건.test(q)) return { 종류: 'client', 제목: '📇 고객' };   // ★기존 카드 엔진에 넘김
  return null;
}

