// 태그를 걷어내고 "사람이 읽는 글자"만 남긴다 — 디자인이 어떻게 감싸든 문구 비교는 되게.
function 글자만(html) {
  return String(html)
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    // ★시안 하단의 설명 줄(.note/.page-h/.top-hint)은 화면 요소가 아니라 팀장 메모다.
    //   "지어낸 숫자 제거함" 같은 메모를 화면 글자로 오해해 잡던 오탐을 막는다.
    //   ★클래스 이름이 정확히 그것일 때만 — "headnote"까지 지우면 머리말이 사라진다(실제로 겪음).
    .replace(/<div[^>]*class=["'](?:[^"']*\s)?(?:note|page-h|top-hint|bg-hint)(?:\s[^"']*)?["'][\s\S]*?<\/div>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'")
    .replace(/\s+/g, ' ').trim();
}
// 띄어쓰기 차이는 봐준다(디자인 줄바꿈 때문). 글자 자체가 다르면 잡는다.
function 헐(s) { return String(s).replace(/\s+/g, ''); }
// ★이모지는 "바뀌어도 되는 것"(대표님 기준). 이모지만 뺀 것은 불일치가 아니라 디자인 판단으로 따로 센다.
//   단 ①②③ · → · · 같은 기호는 내용(순서·구분자)이므로 지우지 않는다.
//   ↗ ▾ ▼ ＋ 같은 장식 기호도 이모지로 본다. 단 → 는 우선순위 구분자(내용)라 남긴다.
const 이모지 = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{23E9}-\u{23FA}\u{FE0F}\u{200D}\u{2197}\u{2196}\u{2198}\u{2199}\u{25B2}-\u{25BF}\u{FF0B}\u{21BB}\u{21A9}]/gu;
function 민(s) { return 헐(String(s).replace(이모지, '')); }

