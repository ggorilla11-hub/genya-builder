function 검사(규칙, 파일) {
  const html = fs.readFileSync(파일, 'utf8');
  const 본문 = 글자만(html);
  const h = 헐(본문), m = 민(본문);
  const 실패 = [], 이모지만 = []; let 통과 = 0;

  규칙.있어야.forEach(([s, why]) => {
    if (h.includes(헐(s))) { 통과++; return; }
    // 이모지를 떼고 보면 있는가 → 디자인 판단(불일치 아님)
    if (민(s) && m.includes(민(s))) { 이모지만.push({ 무엇: s, 왜: why }); 통과++; return; }
    실패.push({ 종류: '빠짐', 무엇: s, 왜: why });
  });
  규칙.없어야.forEach(([s, why]) => {
    if (h.includes(헐(s))) 실패.push({ 종류: '원문에 없음', 무엇: s, 왜: why }); else 통과++;
  });
  if (규칙.순서) {
    const [arr, why] = 규칙.순서;
    const pos = arr.map((s) => h.indexOf(헐(s)));
    const ok = pos.every((p, i) => p >= 0 && (i === 0 || p > pos[i - 1]));
    if (ok) 통과++; else 실패.push({ 종류: '순서', 무엇: arr.join(' → '), 왜: why });
  }
  (규칙.구조 || []).forEach((k) => {
    const c = 구조검사[k]; if (!c) return;
    let r; try { r = c.fn(html); } catch (e) { r = { ok: false, 상세: '오류: ' + e.message }; }
    if (r.ok) 통과++; else 실패.push({ 종류: '구조', 무엇: c.이름, 왜: c.왜 + (r.상세 ? ' → ' + r.상세 : '') });
  });
  return { 통과, 실패, 이모지만 };
}

