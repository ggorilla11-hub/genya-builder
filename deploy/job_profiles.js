function 불러오기(직업) {
  const r = jobKw.찾기(직업);
  const key = r ? r.key : '';
  const 덧 = 덧칠[key] || {};
  const p = {
    직업: 직업 || '', 이름: (r && r.이름) || (직업 || ''), key,
    검색어: jobKw.기본검색어(직업),
    완성도: 덧.완성도 || 기본.완성도,
    비서: (덧.비서 || 기본.비서).slice(),
    채점표: Object.assign({}, 기본.채점표, 덧.채점표 || {}),
    정체성: Object.assign({}, 기본.정체성, 덧.정체성 || {}),
    표에있나: !!r,
  };
  p.안내 = p.완성도 === '표준' ? (덧.안내 || 표준_보험.안내)
    : (p.표에있나 ? 기본.안내
      : '표에 없는 직업이에요 — 검색어와 설정을 직접 넣어주시면 그걸 씁니다(지어내지 않습니다).');
  return p;
}
// 어드민 화면이 한눈에 볼 목록(완성도 포함)
function 전체() {
  return jobKw.목록().map((j) => { const p = 불러오기(j.이름); return { 이름: j.이름, key: p.key, 완성도: p.완성도, 비서수: p.비서.length, 검색어수: p.검색어.length }; });
}

