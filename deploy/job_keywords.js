// 직업 이름이나 job 값으로 찾는다
function 찾기(직업) {
  const s = String(직업 || '').trim();
  if (!s) return null;
  return 표.find((r) => r.key === s.toLowerCase() || r.맞는말.test(s)) || null;
}
// ★기본 검색어. 모르는 직업이면 ★빈 배열(지어내지 않는다).
function 기본검색어(직업) { const r = 찾기(직업); return r ? r.검색어.slice() : []; }
function 직업이름(직업) { const r = 찾기(직업); return r ? r.이름 : ''; }
// 화면이 고르게 보여줄 목록
function 목록() { return 표.map((r) => ({ key: r.key, 이름: r.이름, 검색어: r.검색어.slice() })); }
// ★대표가 넣은 게 있으면 그게 우선, 없을 때만 표에서 채운다
function 채우기(직업, 대표가넣은것) {
  const 내것 = (대표가넣은것 || []).map((k) => String(k || '').trim()).filter(Boolean);
  if (내것.length) return { 검색어: 내것.slice(0, 20), 출처: '대표님이 직접 넣으신 것' };
  const 기본 = 기본검색어(직업);
  return { 검색어: 기본, 출처: 기본.length ? `기본 표(${직업이름(직업)})` : '없음' };
}

module.exports = { 표, 찾기, 기본검색어, 직업이름, 목록, 채우기 };
