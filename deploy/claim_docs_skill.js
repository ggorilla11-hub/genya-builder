// ★기준이 확정된 보험사 — 지금은 삼성화재 1개사.
//   여기 없는 보험사는 "공통 기준만 + 개별 기준은 확인 필요"로 정직히 안내한다.
const 확정_보험사 = ['삼성화재'];

// 인식할 보험사 이름(1단계 claim_form_skill.js와 같은 목록 — 그 파일을 수정하지 않으려고 여기 독립적으로 둔다)
const INSURERS = ['삼성화재', '현대해상', 'DB손해보험', 'DB손보', 'KB손해보험', 'KB손보', '메리츠화재', '메리츠',
  '한화손해보험', '한화손보', '롯데손해보험', '롯데손보', '흥국화재', 'MG손해보험', 'NH농협손해보험', '농협손보',
  '삼성생명', '한화생명', '교보생명', '신한라이프', '동양생명', 'ABL생명', 'KB라이프', '흥국생명', 'NH농협생명'];

// 사고유형 — 확실한 낱말일 때만 정한다. 애매하면 ★정하지 않는다(지어내기 금지).
const 사고유형_규칙 = [
  { 유형: '교통', re: /교통\s*사고|자동차\s*사고|차\s*사고|접촉\s*사고|추돌/ },
  { 유형: '상해', re: /상해|골절|부상|다쳤|다침|다쳐|낙상|넘어져|넘어짐|화상|염좌|삐었|찢어져/ },
  { 유형: '질병', re: /질병|질환|발병|암\s|암을|암으로|디스크|염증|급성|만성/ },
];

// 고객 이름으로 오인하면 안 되는 낱말(1단계와 같은 생각 — 호칭은 사람 이름이 아니다)
const _이름아님 = /^(고객|대표|회장|사장|선생|손님|여러분|사모|실장|부장|과장|팀장|이사|우리|저희|본인|당신)$/;

// ═══════════════════════════════════════════════════════════════
// 2. 문장 읽기 — ★규칙 기반. 확실할 때만 정하고, 모르면 되묻는다.
// ═══════════════════════════════════════════════════════════════
function _norm(x) { return String(x == null ? '' : x).trim(); }

/** 보험사 찾기 — 긴 이름부터 찾아야 'DB손보'가 'DB손해보험'을 가리지 않는다 */
function _보험사(t) {
  const 정렬 = INSURERS.slice().sort((a, b) => b.length - a.length);
  for (const n of 정렬) if (t.includes(n)) return n;
  return null;
}

// 사람 이름이 아닌 것들 — 문장 맨 앞에 올 수 있는 흔한 낱말.
//   ★시험에서 잡힌 실제 오인: "삼성화재 실손 청구" → '삼성화재'를 고객 이름으로 읽었다.
const _이름아닌낱말 = /^(수술|입원|통원|진단|사고|교통|상해|질병|병원|의원|청구|서류|보험|어제|오늘|내일|지난|이번|저번|방금|아까)$/;

/** 이 낱말이 사람 이름일 수 있는가 — 보험사명·담보명·호칭은 사람 이름이 아니다 */
function _사람이름같은가(c) {
  const n = String(c || '').replace(/님$/, '');
  if (n.length < 2 || n.length > 4) return false;
  if (_이름아님.test(n) || _이름아닌낱말.test(n)) return false;
  if (INSURERS.some((i) => i.includes(n))) return false;                       // 삼성화재·흥국생명 …
  for (const spec of Object.values(COVERAGES)) {
    if (spec.별칭.some((a) => a === n || a.includes(n))) return false;         // 실손·진단비 …
  }
  return true;
}

/** 고객 이름 찾기 — "○○님" 우선, 없으면 문장 맨 앞 한글 2~4자. ★확실할 때만. */
function _고객명(t) {
  const 후보 = [];
  let m = t.match(/([가-힣]{2,4})님/);
  if (m) 후보.push(m[1]);
  m = t.match(/^\s*([가-힣]{2,4})(?=[\s,]|$)/);
  if (m) 후보.push(m[1].replace(/님$/, ''));
  for (const c of 후보) if (_사람이름같은가(c)) return c.replace(/님$/, '');
  return null;                                   // ★못 찾으면 지어내지 않는다
}

/** 사고유형 찾기 — 규칙에 걸리는 게 없으면 null(미확인) */
function _사고유형(t) {
  for (const r of 사고유형_규칙) if (r.re.test(t)) return r.유형;
  return null;
}

/**
 * 담보 찾기 — 표준 담보명 배열을 돌려준다.
 * ★'수술'·'입원'처럼 담보인지 상황설명인지 애매한 낱말은 담보로 확정하지 않고 '제안'으로만 돌린다.
 *   (예: "무릎수술로 입원했어 … 실손" → 담보=실손의료비 확정 · 제안=수술비·입원일당)
 */
function _담보(t) {
  const 확정 = [], 제안 = [];
  for (const [표준, spec] of Object.entries(COVERAGES)) {
    if (spec.별칭.some((a) => t.includes(a))) { 확정.push(표준); }
  }
  // 애매한 상황 낱말 → 제안(확정 아님). 이미 확정된 담보는 제안하지 않는다.
  if (/수술/.test(t) && !확정.includes('수술비')) 제안.push('수술비');
  if (/입원/.test(t) && !확정.includes('입원일당')) 제안.push('입원일당');
  return { 확정, 제안 };
}

/**
 * 상황 문장 한 줄 → 무엇을 알아냈는지.
 * @returns {{고객명, 보험사, 보험사확정, 사고유형, 담보:Array, 제안담보:Array, unknown:boolean}}
 */
function parseCase(text) {
  const t = _norm(text);
  const { 확정, 제안 } = _담보(t);
  const 보험사 = _보험사(t);
  return {
    고객명: _고객명(t),
    보험사,
    보험사확정: !!(보험사 && 확정_보험사.includes(보험사)),
    사고유형: _사고유형(t),
    담보: 확정,
    제안담보: 제안,
    unknown: 확정.length === 0,                  // ★담보를 못 정하면 되묻는다
  };
}

// ═══════════════════════════════════════════════════════════════
// 3. 담보 → 필요 서류 (표에서만 꺼낸다)
// ═══════════════════════════════════════════════════════════════
/**
 * @param {Array<string>} 담보목록 표준 담보명
 * @returns {{항목:Array<{담보, 서류:Array, 진단명필요:boolean}>, 확인사항:Array, 모르는담보:Array}}
 */
function docsFor(담보목록) {
  const 항목 = [], 모르는담보 = [];
  (담보목록 || []).forEach((c) => {
    const spec = COVERAGES[c];
    if (!spec) { 모르는담보.push(c); return; }   // ★표에 없으면 만들지 않는다
    항목.push({ 담보: c, 서류: spec.서류.slice(), 진단명필요: !!spec.진단명필요 });
  });
  return { 항목, 확인사항: COMMON.확인사항.slice(), 모르는담보 };
}

// ═══════════════════════════════════════════════════════════════
// 4. 고객 전달용 안내문 — ★법적 문구가 항상 붙는다
// ═══════════════════════════════════════════════════════════════
function buildNotice(info, 서류결과) {
  const 이름 = info.고객명 ? `${info.고객명}님` : '고객님';
  const 회사 = info.보험사 ? info.보험사 + ' ' : '';
  const 담보문 = 서류결과.항목.map((x) => x.담보).join('·');

  let s = `${이름}, ${회사}${담보문} 청구를 위해 아래 서류가 필요합니다.\n\n`;

  // 서류 — 중복 제거(실손+입원일당이면 영수증이 두 번 나오지 않게)
  const 본 = new Set(); const 줄 = [];
  서류결과.항목.forEach((x) => {
    x.서류.forEach((d) => { if (!본.has(d)) { 본.add(d); 줄.push(`· ${d}`); } });
  });
  if (서류결과.항목.some((x) => x.진단명필요) && !본.has(COMMON.진단명필수)) {
    줄.push(`· ${COMMON.진단명필수}`);
  }
  s += 줄.join('\n');

  s += '\n\n[확인해 주세요]\n' + COMMON.확인사항.map((c) => `· ${c}`).join('\n');
  s += '\n\n' + LEGAL;                            // ★강제 부착
  return s;
}

// ═══════════════════════════════════════════════════════════════
// 5. 한 번에 — 문장 → 안내 결과 (라우트가 쓰는 입구)
// ═══════════════════════════════════════════════════════════════
/**
 * @param {string} text  "김철수 무릎수술로 입원했어. 삼성화재 실손."
 * @returns {object} ok / 안내 / 서류 / 안내문 / 법적문구 …  (실패해도 지어내지 않고 되묻는다)
 */
function guide(text) {
  const t = _norm(text);
  if (!t) {
    return { ok: false, unknown: true, 법적문구: LEGAL,
      error: '어떤 상황인지 알려주세요. 예: "김철수 무릎수술로 입원했어. 삼성화재 실손."' };
  }
  const info = parseCase(t);

  // ★담보를 못 알아들었으면 지어내지 않고 되묻는다
  if (info.unknown) {
    return {
      ok: false, unknown: true, 법적문구: LEGAL,
      parsed: info,
      error: '어떤 담보로 청구하시는지 알려주세요.',
      선택지: Object.keys(COVERAGES),
      예시: '예) "김철수 무릎수술 삼성화재 실손" · "박영희 입원일당" · "이철수 후유장해"',
    };
  }

  const 서류 = docsFor(info.담보);

  // ── 정직 표시들 ──
  const 알림 = [];
  if (!info.보험사) {
    알림.push('보험사를 말씀 안 하셔서 손보사 공통 기준으로 안내했어요. 회사를 알려주시면 더 정확해집니다.');
  } else if (!info.보험사확정) {
    알림.push(`${info.보험사}는 아직 개별 기준이 등록되어 있지 않아요. 손보사 공통 기준으로 안내했고, `
      + `${info.보험사} 개별 기준은 ★보험사 확인이 필요합니다. (현재 확정: ${확정_보험사.join('·')})`);
  }
  if (!info.사고유형) {
    알림.push('사고유형(질병·상해·교통)을 못 알아들었어요. 유형에 따라 보험사가 서류를 더 요구할 수 있으니 확인해 주세요.');
  } else if (info.사고유형 !== '질병') {
    알림.push(`${info.사고유형} 건은 사고 경위를 확인하는 서류를 보험사가 추가로 요구할 수 있어요. ★보험사 확인이 필요합니다.`);
  }
  if (info.제안담보.length) {
    알림.push(`말씀에 "${info.제안담보.map((c) => c === '수술비' ? '수술' : '입원').join('·')}"이 있어요. `
      + `${info.제안담보.join('·')} 담보도 함께 청구하신다면 서류가 추가로 필요합니다 — 말씀해 주시면 같이 안내할게요.`);
  }

  return {
    ok: true,
    고객명: info.고객명,
    보험사: info.보험사,
    보험사확정: info.보험사확정,
    사고유형: info.사고유형,
    담보: info.담보,
    서류: 서류.항목,
    진단명안내: COMMON.진단명필수,
    확인사항: 서류.확인사항,
    알림,
    안내문: buildNotice(info, 서류),
    법적문구: LEGAL,                                // ★화면이 빼먹어도 결과에는 항상 있다
    안내: '지니야가 기준표로 정리한 참고 안내입니다. ★제출 전 보험사·약관을 확인하세요.',
  };
}

